#!/usr/bin/env python3
"""Dev-time generator for the built-in AutoEQ profiles. Run manually; the apps never go online.

Downloads AutoEQ results (https://github.com/jaakkopasanen/AutoEq, MIT license,
Copyright (c) 2018-2022 Jaakko Pasanen) for the supported earbud brand, fits the app's
10 bands to each GraphicEQ correction and writes plain data files for both apps.

Usage: [GITHUB_TOKEN=...] python3 tools/autoeq/gen_autoeq.py
"""
import json, os, sys, urllib.parse, urllib.request
sys.path.insert(0, os.path.dirname(__file__))
from autoeq_fit import FREQS, fit, graphic_at, parse_graphic

REPO = "jaakkopasanen/AutoEq"
BRAND = "TOZO "
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = [os.path.join(ROOT, "windows", "BluntyBuds.Proto", "autoeq_profiles.tsv"),
       os.path.join(ROOT, "android", "app", "src", "main", "assets", "autoeq_profiles.tsv")]


def get(url):
    h = {"User-Agent": "bluntybuds-gen"}
    if os.environ.get("GITHUB_TOKEN") and "api.github.com" in url:
        h["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]  # optional, avoids API rate limits
    req = urllib.request.Request(url, headers=h)
    with urllib.request.urlopen(req) as r:
        return r.read().decode("utf-8")


def main():
    sha = json.loads(get(f"https://api.github.com/repos/{REPO}/commits/master"))["sha"]
    tree = json.loads(get(f"https://api.github.com/repos/{REPO}/git/trees/{sha}?recursive=1"))["tree"]
    rows = {}
    for p in sorted(t["path"] for t in tree):
        parts = p.split("/")
        if parts[0] != "results" or not parts[-1].endswith(" GraphicEQ.txt") or not parts[-2].startswith(BRAND):
            continue
        model = parts[-2][len(BRAND):]
        if model in rows:
            continue  # first source (alphabetical) wins
        text = get(f"https://raw.githubusercontent.com/{REPO}/{sha}/" + urllib.parse.quote(p))
        pts = parse_graphic(text)
        gains = fit([graphic_at(pts, f) for f in FREQS])
        rows[model] = (parts[1] + " " + parts[2], gains)
    lines = ["# AutoEQ profiles fitted to the 10-band EQ (Hz: " + " ".join(map(str, FREQS)) + ").",
             "# Source: AutoEq by Jaakko Pasanen, MIT license, https://github.com/" + REPO + " commit " + sha,
             "# Generated by tools/autoeq/gen_autoeq.py. Columns: model<TAB>measurement<TAB>10 gains in dB."]
    for m in sorted(rows):
        src, g = rows[m]
        lines.append(m + "\t" + src + "\t" + ",".join(f"{x:g}" for x in g))
    data = "\n".join(lines) + "\n"
    for o in OUT:
        os.makedirs(os.path.dirname(o), exist_ok=True)
        with open(o, "w", newline="\n") as f:
            f.write(data)
    print(data)


if __name__ == "__main__":
    main()
